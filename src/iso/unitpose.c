/* The game logic, 0x100e4c70-0x100e5814: the animation a unit plays for its action, turning
 * and moving. The four tables give it per action (0-0x4c); values from 0xf0 are worked out. */
#include "iso_core.h"
#include "unitpose.h"

#define F0_ATTACK 0xf0 /* attack type 1: 0x4a, else 1 */
#define F1_ATTACK 0xf1 /* attack type 1: 0x0c, else 1 */
#define F2_ATTACK 0xf2 /* attack type 1: 0x08, else 1 */
#define F3_TYPE19 0xf3 /* type 0x19: 0x40, else the table's default */
#define F4_WALK 0xf4
#define F5_SIDE_D 0xf5
#define F6_SIDE_E 0xf6
#define NODE_FLAGS(k) P(uint16_t, I(uint8_t *, 0x1984) + (k) * 0x12, 0xa)
#define TURN_NEEDED(d, n) G(int8_t, 0x1015b620 + (d) + (n) * 8)
#define TURN_SIDE(d, n) G(int8_t, 0x1015b5a0 + (d) + (n) * 8)
#define TURN_NEXT(d, n) G(uint8_t, 0x1015b5e0 + (d) + (n) * 8)
/* the original returns only AL; the rest of EAX is what the path left there, and callers
 * hand the whole register on to the network code */
#define WITH_HIGH(p, pose) (((uint32_t)(uintptr_t)(p) & 0xffffff00) | (pose))

